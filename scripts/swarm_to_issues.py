@dataclass
class SwarmIssue:
    """A single parsed issue ready for import."""

    issue_id: str
    role: str
    title: str
    body: str
    labels: list[str] = field(default_factory=list)

    @property
    def role_label(self) -> str:
        return ROLE_LABEL.get(self.role, "swarm-unknown")

    @property
    def dedup_key(self) -> str:
        """Stable identifier used for idempotent re-runs."""
        return f"{self.role}:{self.issue_id}"


@dataclass
class ImportResult:
    created: list[SwarmIssue] = field(default_factory=list)
    skipped_existing: list[SwarmIssue] = field(default_factory=list)
    skipped_duplicate_in_batch: list[SwarmIssue] = field(default_factory=list)
    errors: list[tuple[SwarmIssue, str]] = field(default_factory=list)

    @property
    def total(self) -> int:
        return len(self.created) + len(self.skipped_existing) + len(self.errors)

    @property
    def ok(self) -> bool:
        return not self.errors


