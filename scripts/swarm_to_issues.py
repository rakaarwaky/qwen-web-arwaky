ROLE_DETECT = re.compile(r"####\s+Issue\s+([A-Z]+-\d+-\d+)\s*$")


def _strip_md_escapes(s: str) -> str:
    """Strip markdown escape backslashes, iterating until stable."""
    prev = None
    while prev != s:
        prev = s
        out = []
        i = 0
        while i < len(s):
            c = s[i]
            if c == "\\" and i + 1 < len(s) and s[i + 1] in "[]`_*\\":
                out.append(s[i + 1])
                i += 2
            else:
                out.append(c)
                i += 1
        s = "".join(out)
    return s


def build_issue_body(
    role: str,
    iid: str,
    description: str,
    plan_title: str,
    swarm_id: str,
    open_questions: str = "",
) -> str:
    parts = [
        f"## {ROLE_SCOPE_NOTE.get(role, 'Swarm review')}",
        "",
        f"**Agent**: `{role}`",
        "",
        f"**Swarm Run**: `{swarm_id}`",
    ]
    if plan_title:
        parts += ["", f"**Source Plan**: {plan_title}"]
    parts += ["", f"**Issue ID**: `{iid}`", "", "---", "", description]
    if open_questions.strip().lower() not in ("", "none", "-"):
        parts += ["", "## Open Questions", open_questions.strip()]
    parts += ["", "---", ""]
    parts.append(f"*Auto-created from qwen-web-arwaky swarm run `{swarm_id}` (`{role}`); imported `{iid}`.*")
    return "\n".join(parts)


def parse_agent_output(role: str, path: Path, swarm_id: str) -> list[SwarmIssue]:
    """Extract every ``#### Issue`` block from one agent's output.md."""
    text = path.read_text(encoding="utf-8", errors="replace")

    plan_title = ""
    for ln in text.splitlines():
        if ln.startswith("# "):
            plan_title = ln[2:].strip()
            break

    issues: list[SwarmIssue] = []
    cur: dict | None = None
    collecting_desc: str | None = None
    in_code = False
    code_lines: list[str] = []

    def flush() -> None:
        nonlocal cur, collecting_desc, in_code
        if cur is not None:
            desc = "\n".join(cur["desc"]).strip()
            open_q = "\n".join(cur["open_q"]).strip()
            if cur.get("title"):
                body = build_issue_body(cur["role"], cur["id"], desc, plan_title, swarm_id, open_q)
                # Labels: explicit list from the template first, else infer
                # role + severity from the title.
                if cur.get("explicit_labels"):
                    labels: list[str] = [cur["role_label"]] + cur["explicit_labels"]
                else:
                    labels = [cur["role_label"]]
                    for sev in SEVERITY_LABELS:
                        if f"[{sev.upper()}]" in cur["title"]:
                            labels.append(f"severity-{sev}")
                seen_lbls: set[str] = set()
                labels = [lbl for lbl in labels if not (lbl in seen_lbls or seen_lbls.add(lbl))]
                issues.append(
                    SwarmIssue(
                        issue_id=cur["id"],
                        role=cur["role"],
                        title=cur["title"],
                        body=body,
                        labels=labels,
                    )
                )
        cur = None
        collecting_desc = None
        in_code = False

    for ln in text.splitlines():
        m = ROLE_DETECT.match(ln)
        if m:
            flush()
            prefix = m.group(1).split("-")[0]
            # Map the issue-id prefix back to a registered role when possible
            role_by_prefix = next(
                (r for r, p in ROLE_PREFIX.items() if p == prefix),
                role,
            )
            cur = {
                "id": m.group(1),
                "role": role_by_prefix,
                "role_label": ROLE_LABEL.get(role_by_prefix, "swarm-unknown"),
                "title": "",
                "desc": [],
                "open_q": [],
                "explicit_labels": [],
            }
            collecting_desc = None
            in_code = False
            code_lines = []
            continue

        if cur is None:
            continue

        if in_code:
            code_lines.append(ln)
            if ln.strip().startswith("```"):
                in_code = False
                cur["desc"].extend(code_lines)
                code_lines = []
            continue

        stripped = ln.strip()
        if stripped.startswith("```"):
            # If the current field is description-ish, the fenced block belongs to it
            in_code = True
            code_lines = [ln]
            continue

        tm = re.match(r"^-\s*\*\*Title\*\*:\s*(.+)$", ln)
        if tm:
            cur["title"] = _strip_md_escapes(tm.group(1).strip())
            collecting_desc = None
            continue

        lml = re.match(r"^-\s*\*\*Label\*\*:\s*(.*)$", ln)
        if lml:
            raw = lml.group(1).strip()
            # Accept a `{a|b|c}` candidate list (pipe-separated) or a plain
            # comma-separated list; both are normalised to one label each.
            if raw.startswith("{") and raw.endswith("}"):
                raw = raw[1:-1]
            if raw:
                parts = re.split(r"[,|]", raw)
                seen: set[str] = set()
                cur["explicit_labels"] = [
                    p.strip() for p in parts if p.strip() and not (p.strip() in seen or seen.add(p.strip()))
                ]
            collecting_desc = None
            continue

        om = re.match(r"^-\s*\*\*Open Questions\*\*:\s*(.*)$", ln)
        if om:
            rest = om.group(1).strip()
            if rest:
                cur["open_q"].append(rest)
            collecting_desc = "open_q"
            continue

        lm = re.match(r"^-\s*\*\*Location Path\*\*:?\s*(.*)$", ln)
        if lm:
            cur["desc"].append("## Location Path")
            rest = lm.group(1).strip()
            if rest:
                cur["desc"].append(rest)
            collecting_desc = "desc"
            continue

        dm = re.match(r"^-\s*\*\*(Description)\*\*:\s*(.*)$", ln)
        if dm:
            cur["desc"].append("## Description")
            if dm.group(2).strip():
                cur["desc"].append(dm.group(2).strip())
            collecting_desc = "desc"
            continue

        am = re.match(r"^-\s*\*\*(Acceptance Criteria)\*\*:\s*(.*)$", ln)
        if am:
            cur["desc"].append("## Acceptance Criteria")
            if am.group(2).strip():
                cur["desc"].append(am.group(2).strip())
            collecting_desc = None
            continue

        rm = re.match(r"^-\s*\*\*(Recommendation)\*\*:\s*(.*)$", ln)
        if rm:
            cur["desc"].append("## Recommendation")
            if rm.group(2).strip():
                cur["desc"].append(rm.group(2).strip())
            collecting_desc = None
            continue

        gm = re.match(r"^-\s*\*\*(Git Diff)\*\*:\s*$", ln)
        if gm:
            cur["desc"].append("## Suggested Diff")
            collecting_desc = None
            continue

        # Plain continuation lines while inside an active field block
        if collecting_desc and stripped and not stripped.startswith("- **"):
            if collecting_desc == "open_q":
                if stripped.lower() not in ("none", "-", "n/a"):
                    cur["open_q"].append(ln.rstrip())
            else:
                cur["desc"].append(ln.rstrip())
            continue

        # Generic sub-bullets (e.g. "**Severity**: ...") — keep them
        if stripped.startswith("- **") and not re.match(
            r"^-\s*\*\*(Title|Label|Location Path|Description|Acceptance "
            r"Criteria|Recommendation|Git Diff|Open Questions)\*\*",
            stripped,
        ):
            cur["desc"].append(stripped)

    flush()

    # If no structured issues found, fall back to whole-document summary
    if not issues and text.strip():
        issues.append(
            SwarmIssue(
                issue_id=f"DOC-{swarm_id[-4:]}",
                role=role,
                title=f"[{role}] Swarm output (unstructured) — {plan_title[:40]}",
                body=(
                    f"## {ROLE_SCOPE_NOTE.get(role, 'Swarm review')}\n\n"
                    f"**Agent**: `{role}`\n\n**Swarm Run**: `{swarm_id}`\n\n"
                    "---\n\n" + text.strip() + "\n"
                ),
                labels=[ROLE_LABEL.get(role, "swarm-unknown")],
            )
        )
    return issues


def parse_swarm_run(run: Path) -> list[SwarmIssue]:
    """Parse every ``*/output.md`` in a swarm run directory."""
    manifest = read_manifest(run)
    swarm_id = manifest.get("swarm_id", run.name)
    out: list[SwarmIssue] = []
    for d in sorted(run.iterdir()):
        if not d.is_dir():
            continue
        role = d.name
        outmd = d / "output.md"
        if not outmd.is_file():
            continue
        out.extend(parse_agent_output(role, outmd, swarm_id))
    # De-dup by (role, issue_id) — keep first occurrence
    seen: set[tuple[str, str]] = set()
    deduped: list[SwarmIssue] = []
    for it in out:
        key = (it.role, it.issue_id)
        if key not in seen:
            seen.add(key)
            deduped.append(it)
    return deduped


# ---------------------------------------------------------------------------
# GitHub client (stdlib only; token from `gh auth token` or GITHUB_TOKEN)
# ---------------------------------------------------------------------------


class GitHubClient:
    def __init__(self, base_url: str = "https://api.github.com", repo: str = ""):
        self.base_url = base_url.rstrip("/")
        self._repo = repo
        self._token: str | None = None

    def authenticate(self) -> None:
        token = os.environ.get("GITHUB_TOKEN") or os.environ.get("GH_TOKEN")
        if not token:
            gh = shutil.which("gh")
            if gh:
                try:
                    token = subprocess.run(
                        [gh, "auth", "token"],
                        capture_output=True,
                        text=True,
                        check=False,
                    ).stdout.strip()
                except OSError:
                    token = ""
        if not token:
            raise SystemExit("No GitHub token found. Set GITHUB_TOKEN or log in with `gh auth login`.")
        self._token = token

    def _req(self, method: str, path: str, payload: dict | None = None):
        # URL-encode the path (and its query string) so spaces / backticks /
        # other control characters are handled by urllib.request safely.
        url = f"{self.base_url}{urllib.parse.quote(path, safe='/:?&=')}"
        headers = {
            "Authorization": f"Bearer {self._token}",
            "Accept": "application/vnd.github+json",
        }
        data = None
        if payload is not None:
            headers["Content-Type"] = "application/json"
            data = json.dumps(payload).encode()
        req = urllib.request.Request(url, data=data, headers=headers, method=method)
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:
                raw = resp.read()
                return json.loads(raw) if raw else {}
        except urllib.error.HTTPError as e:
            err_body = e.read().decode(errors="replace")
            raise RuntimeError(f"GitHub API {method} {path} -> HTTP {e.code}: {err_body[:500]}") from e

    def list_labels(self) -> set[str]:
        labels = set()
        page = 1
        while True:
            batch = self._req(
                "GET",
                f"/repos/{self._repo}/labels?per_page=100&page={page}",
            )
            labels.update(entry["name"].lower() for entry in batch)
            if len(batch) < 100:
                break
            page += 1
        return labels

    def ensure_label(self, name: str, existing: set[str]) -> None:
        if name.lower() in existing:
            return
        color = LABEL_COLORS.get(name, "BFD4F2")
        try:
            self._req(
                "POST",
                f"/repos/{self._repo}/labels",
                {"name": name, "color": color, "description": name},
            )
            existing.add(name.lower())
            print(f"  + label created: {name}")
        except RuntimeError as e:
            # May be a race (label created in parallel) — warn and continue.
            print(f"  ! label {name}: {e}")

    def find_open_issue_number(self, issue: SwarmIssue) -> int | None:
        """Return the number of an open issue that matches this issue, else None.

        Dedup key is the stable ``Issue ID`` marker embedded in the body
        (e.g. ``BE-1-001``), which is far more reliable than matching the
        full human-readable title. The query is built raw; ``_req`` handles
        URL-encoding.
        """
        marker = f"imported `{issue.issue_id}`"
        q = f"repo:{self._repo} is:issue is:open {marker}"
        try:
            res = self._req("GET", f"/search/issues?q={q}&per_page=5")
            for item in res.get("items", []):
                body = item.get("body") or ""
                if f"imported `{issue.issue_id}`" in body:
                    return int(item["number"])
        except RuntimeError:
            pass
        return None

    def create_issue(self, title: str, body: str, labels: list[str]) -> int:
        payload = {"title": title, "body": body, "labels": labels}
        res = self._req("POST", f"/repos/{self._repo}/issues", payload)
        return int(res["number"])


