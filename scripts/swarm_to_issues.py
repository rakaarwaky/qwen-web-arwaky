def _prompt(text: str) -> str:
    try:
        return input(text).strip()
    except (EOFError, KeyboardInterrupt) as err:
        print("\nAborted.")
        raise SystemExit(1) from err


def _prompt_choice(prompt: str, choices: list[str], allow_input: bool = True) -> str:
    """Numbered selection with free-text fallback."""
    print(prompt)
    for i, c in enumerate(choices, 1):
        print(f"  {i:2d}) {c}")
    if allow_input:
        extra = "  m) manual entry"
        print(extra)
    while True:
        val = _prompt(f"Select 1-{len(choices)}" + (" or m" if allow_input else "") + ": ")
        if val.isdigit() and 1 <= int(val) <= len(choices):
            return choices[int(val) - 1]
        if allow_input and val.lower() == "m":
            return _prompt("Enter value: ")
        print("Invalid selection, try again.")


def detect_local_github_projects() -> list[tuple[str, str]]:
    """Heuristically detect `owner/repo` values from local git worktrees.

    Looks for .git config files whose origin URL matches a GitHub repo and
    collects the (owner, repo) pairs it has already seen.
    """
    projects: list[tuple[str, str]] = []
    seen: set[tuple[str, str]] = set()
    git_cfg_candidates = []
    home = Path.home()
    for root in (home / ".orca" / "workspaces", home / "workspaces", home):
        git_cfg_candidates.extend(root.glob("*/.git"))
        git_cfg_candidates.extend(root.glob("*/.git/config"))
    for p in git_cfg_candidates:
        cfg = p if p.name == "config" else p / "config"
        if not cfg.is_file():
            continue
        try:
            content = cfg.read_text(encoding="utf-8", errors="replace")
        except OSError:
            continue
        m = re.search(
            r"url\s*=\s*(?:https?://|git@)github\.com[:/]([\w.-]+)/([\w.-]+?)(?:\.git)?\s*$",
            content,
            re.MULTILINE,
        )
        if m:
            owner, repo = m.group(1), m.group(2)
            key = (owner, repo)
            if key not in seen:
                seen.add(key)
                projects.append(key)
    # Always include the known repo as a hint
    known = ("rakaarwaky", "qwen-web-arwaky")
    if known not in seen:
        projects.insert(0, known)
    return projects


def prompt_swarm_folder() -> Path:
    default_root = Path.home() / ".local" / "share" / "qwen-web-arwaky" / "swarm"
    found = discover_swarm_runs(default_root) if default_root.is_dir() else []
    print("Swarm run candidates under ~/.local/share/qwen-web-arwaky/swarm:")
    if not found:
        print("  (none found — you will be asked to type a path)")
    for i, p in enumerate(found, 1):
        man = read_manifest(p)
        status = man.get("status", "?")
        completed = man.get("completed", 0)
        total = man.get("agent_count", 0)
        print(f"  {i:2d}) {p}  [{status} {completed}/{total} agents]")
    choices = [str(p) for p in found]
    val = _prompt_choice("Pick a swarm run:", choices, allow_input=True)
    if val == "":
        val = _prompt("Type the path to a swarm run directory: ")
    p = Path(val)
    if not p.is_dir() or not (p / "manifest.json").is_file():
        raise SystemExit(f"Not a swarm run directory (missing manifest.json): {p}")
    return p.resolve()


def prompt_repo(detected: list[tuple[str, str]]) -> str:
    choices = [f"{o}/{r}" for o, r in detected]
    val = _prompt_choice("Target GitHub project (owner/repo):", choices, allow_input=True)
    if not re.match(r"^[\w.-]+/[\w.-]+$", val):
        raise SystemExit(f"Invalid owner/repo value: {val}")
    return val


