def discover_swarm_runs(base: Path) -> list[Path]:
    """Find swarm run directories (containing a manifest.json) under ``base``.

    ``base`` may point directly at a run directory or at a directory that
    contains one or more runs.
    """
    if not base.is_dir():
        return []
    runs: list[Path] = []
    if (base / "manifest.json").is_file():
        runs.append(base)
    for sub in sorted(base.iterdir()):
        if sub.is_dir() and (sub / "manifest.json").is_file():
            runs.append(sub)
    # Deeper nesting (swarm_root/swarm_*/<run>):
    if not runs:
        for sub in sorted(base.iterdir()):
            if sub.is_dir():
                for deeper in sorted(sub.iterdir()):
                    if deeper.is_dir() and (deeper / "manifest.json").is_file():
                        runs.append(deeper)
    # De-dup, keep order
    seen: set[Path] = set()
    out: list[Path] = []
    for r in runs:
        rp = r.resolve()
        if rp not in seen:
            seen.add(rp)
            out.append(r)
    return out


def read_manifest(run: Path) -> dict:
    try:
        return json.loads((run / "manifest.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}


