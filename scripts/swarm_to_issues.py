#!/usr/bin/env python3
"""Import qwen-web-arwaky swarm agent outputs as GitHub Issues.

Reads every ``*/output.md`` in a swarm run directory, extracts the structured
``#### Issue`` blocks generated by the role templates, and creates matching
GitHub Issues in a target repository. Interactive mode walks the user through
folder selection, project selection, preview, and confirmation.

No external dependencies beyond the standard library; GitHub is accessed
directly over the REST API using a ``gh`` auth token or ``GITHUB_TOKEN``.

Usage:
    # Fully interactive (prompts for folder, project, preview):
    python3 scripts/swarm_to_issues.py

    # Non-interactive:
    python3 scripts/swarm_to_issues.py --folder /path/to/swarm --repo owner/repo --yes
    python3 scripts/swarm_to_issues.py --folder /path/to/swarm --repo owner/repo --dry-run

Exit codes:
    0 success (or dry-run completed)
    1 fatal error (no issues found, auth failure, user abort, ...)
"""

