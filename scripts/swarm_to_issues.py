def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--folder", help="Swarm run directory (default: prompt)")
    ap.add_argument("--repo", help="GitHub owner/repo (default: prompt)")
    ap.add_argument(
        "--dry-run",
        action="store_true",
        help="Parse and preview only; do not call the GitHub API",
    )
    ap.add_argument(
        "--yes",
        "-y",
        action="store_true",
        help="Skip interactive confirmation; create all issues immediately",
    )
    ap.add_argument(
        "--no-dedup",
        action="store_true",
        help="Disable dedup against open issues with the same title",
    )
    args = ap.parse_args()

    folder = Path(args.folder).resolve() if args.folder else prompt_swarm_folder()
    print(f"\nSwarm run: {folder}")

    issues = parse_swarm_run(folder)
    if not issues:
        print("No structured issues found in the swarm run output.", file=sys.stderr)
        sys.exit(1)

    print_preview(issues)

    if args.dry_run:
        print("--dry-run: stopping before any GitHub API calls.")
        return

    repo = args.repo or prompt_repo(detect_local_github_projects())
    print(f"\nTarget repo: {repo}")

    client = GitHubClient(repo=repo)
    client.authenticate()
    print("Authenticated.")

    existing_labels = client.list_labels()
    needed = sorted({lbl for it in issues for lbl in it.labels})
    for lbl in needed:
        client.ensure_label(lbl, existing_labels)

    created = 0
    skipped_existing = 0
    skipped_dup_in_batch = 0
    err_count = 0

    seen_titles: set[str] = set()
    for it in issues:
        # In-batch duplicate guard (same title twice in one run)
        if it.title in seen_titles:
            skipped_dup_in_batch += 1
            continue
        seen_titles.add(it.title)

        if not args.no_dedup:
            existing_num = client.find_open_issue_number(it)
            if existing_num is not None:
                print(f"  = already open #{existing_num} (skip): {it.title[:56]}")
                skipped_existing += 1
                continue

        try:
            num = client.create_issue(it.title, it.body, it.labels)
            print(f"  + created #{num}: {it.title[:56]}")
            created += 1
        except RuntimeError as e:
            print(f"  ! ERROR {it.title[:56]}: {e}", file=sys.stderr)
            err_count += 1
        # tiny backoff to respect rate limits
        if not args.yes and created % 20 == 0 and created:
            import time

            time.sleep(0.5)

    print(
        f"\nDone. created={created} skipped_existing={skipped_existing} "
        f"duplicate_in_batch={skipped_dup_in_batch} errors={err_count}"
    )
    if err_count:
        sys.exit(1)


if __name__ == "__main__":
    main()
